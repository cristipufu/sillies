#!/usr/bin/env python3
"""Generate the pure Swift lookup from a local WHATWG entities.json snapshot."""

import argparse
import hashlib
import json
from pathlib import Path
import tempfile


def swift_string(value):
    return '"' + ''.join(f'\\u{{{ord(character):X}}}' for character in value) + '"'


def render(source):
    payload = source.read_bytes()
    entries = json.loads(payload)
    references = {}
    for name, entry in entries.items():
        if name.startswith('&') and name.endswith(';'):
            characters = entry['characters']
            if [ord(character) for character in characters] != entry['codepoints']:
                raise ValueError(f'Character/codepoint mismatch: {name}')
            references[name[1:-1]] = characters
    if not references:
        raise ValueError('The snapshot has no terminated character references')
    lines = [
        '// Generated by scripts/generate-html-character-references.py; do not edit by hand.',
        '// Source: https://html.spec.whatwg.org/entities.json',
        f'// Source SHA-256: {hashlib.sha256(payload).hexdigest()}',
        '// Copyright © WHATWG (Apple, Google, Mozilla, Microsoft).',
        '// BSD 3-Clause for incorporated source; see Resources/Licenses/WHATWG-HTML.txt.',
        '',
        'enum HTMLNamedCharacterReferences {',
        f'  static let maximumNameLength = {max(map(len, references))}',
        '  static let values: [String: String] = [',
    ]
    lines.extend(f'    "{name}": {swift_string(value)},' for name, value in sorted(references.items()))
    return '\n'.join(lines + ['  ]', '}', ''])


def write_atomic(destination, content):
    with tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', dir=destination.parent, delete=False) as stream:
        temporary = Path(stream.name)
        try:
            stream.write(content)
            stream.flush()
            temporary.chmod(0o644)
            temporary.replace(destination)
        finally:
            temporary.unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path, help='Downloaded https://html.spec.whatwg.org/entities.json')
    arguments = parser.parse_args()
    destination = Path(__file__).resolve().parents[1] / 'Sources/SilliesCore/HTMLNamedCharacterReferences.swift'
    try:
        write_atomic(destination, render(arguments.source))
    except (OSError, ValueError, KeyError, TypeError) as error:
        parser.exit(1, f'Character-reference generation failed: {error}\n')
    print(f'Generated {destination.name}')


if __name__ == '__main__':
    main()
