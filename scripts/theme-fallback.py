#!/usr/bin/env python3
"""Keep the initial in-memory Sillies colors generated from the default JSON palette."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'Sources/SilliesDesign/Themes/sillies.json'
OUTPUT = ROOT / 'Sources/SilliesApp/UI/DefaultThemeColors.swift'

def render():
    definition = json.loads(SOURCE.read_text())
    lines = ['// Generated by scripts/theme-fallback.py from sillies.json. Do not edit.',
             'import AppKit', 'import SilliesDesign', '',
             'enum DefaultThemeColors {',
             '  static func color(_ role: ThemeColorRole, appearance: NSAppearance) -> NSColor {',
             '    let dark = appearance.bestMatch(from: [.aqua, .darkAqua]) == .darkAqua',
             '    let hex: String', '    switch role {']
    for role, light in definition['light'].items():
        dark = definition['dark'][role]
        lines.append(f'    case .{role}: hex = dark ? "{dark[1:]}" : "{light[1:]}"')
    lines += ['    }', '    return NSColor(hex: hex)', '  }', '}', '']
    return '\n'.join(lines)

if __name__ == '__main__':
    result = render()
    if '--check' in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text() != result:
            sys.exit('Default theme colors are stale; run python3 scripts/theme-fallback.py')
    else:
        OUTPUT.write_text(result)
